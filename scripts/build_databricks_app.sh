#!/usr/bin/env bash
# Build the combined Findora Databricks App package: FastAPI API + compiled frontend.
#
# Usage (from anywhere):
#   scripts/build_databricks_app.sh [output_dir]      # default: build/databricks-app (git-ignored)
#   SKIP_NPM_CI=1 scripts/build_databricks_app.sh     # reuse existing frontend/node_modules
#
# The output folder is the App source root to deploy. It contains ONLY:
#   app.yaml, requirements.txt, server.py, backend/app/**/*.py (no tests), static/index.html
# Tests, mocks, fixtures, .env files, Databricks ingestion assets and node_modules are never copied.
# The script fails if a required input is missing or if anything outside that allow-list is packaged.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/deploy/findora-app"
OUT="${1:-$ROOT/build/databricks-app}"
MARKER=".findora-app-staging"

fail() { echo "build_databricks_app: ERROR: $*" >&2; exit 1; }
info() { echo "build_databricks_app: $*"; }

# --- Required inputs ---------------------------------------------------------------
for file in deploy/findora-app/server.py deploy/findora-app/app.yaml deploy/findora-app/requirements.txt \
            backend/app/main.py frontend/index.html frontend/package.json frontend/package-lock.json; do
  [ -f "$ROOT/$file" ] || fail "missing required file: $file"
done
command -v npm >/dev/null 2>&1 || fail "npm is required to build the frontend"
command -v tar >/dev/null 2>&1 || fail "tar is required to copy backend sources"

# --- Safe, repeatable output folder ------------------------------------------------
mkdir -p "$(dirname "$OUT")"
OUT="$(cd "$(dirname "$OUT")" && pwd)/$(basename "$OUT")"
case "$OUT" in
  "/"|"$HOME"|"$ROOT"|"$ROOT/frontend"|"$ROOT/backend"|"$ROOT/deploy"*|"$ROOT/databricks"*)
    fail "refusing to use $OUT as the output folder" ;;
esac
if [ -e "$OUT" ]; then
  # Only delete a folder this script created before (it carries the marker file).
  [ -f "$OUT/$MARKER" ] || fail "$OUT exists and was not created by this script; choose another output folder"
  rm -rf "$OUT"
fi
mkdir -p "$OUT/static"
echo "Generated by scripts/build_databricks_app.sh; safe to delete." > "$OUT/$MARKER"

# --- Frontend: same-origin API build -------------------------------------------------
info "building frontend (VITE_API_URL=same-origin)"
(
  cd "$ROOT/frontend"
  if [ "${SKIP_NPM_CI:-0}" != "1" ]; then
    npm ci --no-audit --no-fund >/dev/null || exit 1
  fi
  [ -x node_modules/.bin/vite ] || { echo "vite not installed; run without SKIP_NPM_CI=1" >&2; exit 1; }
  VITE_API_URL=same-origin VITE_DEFAULT_MODE=api node_modules/.bin/vite build --outDir "$OUT/static" --emptyOutDir --logLevel warn
) || fail "frontend build failed"
[ -f "$OUT/static/index.html" ] || fail "frontend build did not produce static/index.html"
grep -q "const ENV_API_URL = 'same-origin'" "$OUT/static/index.html" || fail "built frontend is not configured for same-origin API"
grep -q "const ENV_DEFAULT_MODE = 'api'" "$OUT/static/index.html" || fail "built frontend does not default to API mode"

# --- Backend: runtime Python sources only ---------------------------------------------
info "copying backend/app runtime sources"
(cd "$ROOT" && find backend/app -type f -name '*.py' -not -path '*/__pycache__/*' -not -path '*/tests/*' -not -name 'test_*.py' -print0 \
  | tar --null -T - -cf -) | (cd "$OUT" && tar -xf -)
[ -f "$OUT/backend/app/main.py" ] || fail "backend copy did not include backend/app/main.py"

# --- App entry point and configuration ------------------------------------------------
cp "$SRC/server.py" "$SRC/app.yaml" "$SRC/requirements.txt" "$OUT/"

# --- Verification: allow-list + secret scan ------------------------------------------
unexpected="$(cd "$OUT" && find . -type f \
  ! -path './app.yaml' ! -path './requirements.txt' ! -path './server.py' ! -path "./$MARKER" \
  ! -path './static/index.html' ! -path './backend/app/*.py' -print)"
[ -z "$unexpected" ] || fail "unexpected files in package:
$unexpected"
forbidden="$(cd "$OUT" && find . \( -iname '.env*' -o -iname '*mock*' -o -iname '*fixture*' -o -iname 'test*' \
  -o -name 'node_modules' -o -name 'databricks' -o -iname '*.pem' -o -iname '*.key' \) -print)"
[ -z "$forbidden" ] || fail "forbidden paths in package:
$forbidden"
if grep -R -n -I -E 'dapi[0-9a-f]{32}|SERPAPI_API_KEY *= *[^ ]+|DATABRICKS_TOKEN *= *[^ ]+|DATABRICKS_CLIENT_SECRET *= *[^ ]+|-----BEGIN [A-Z ]*PRIVATE KEY' "$OUT" >/dev/null; then
  fail "possible secret found in package; inspect $OUT"
fi
if grep -q -E 'mock-api|discover-fixtures|127\.0\.0\.1:8001' "$OUT/static/index.html"; then
  fail "mock API references found in built frontend"
fi

info "package ready: $OUT"
(cd "$OUT" && find . -type f ! -name "$MARKER" | sort | sed 's/^\.\//  /')
info "deploy this folder as the Databricks App source root (not deploy/findora-app itself)."
